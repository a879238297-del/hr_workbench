def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # 工资表
    wb_p = openpyxl.Workbook()
    ws_p = wb_p.active
    ws_p.title = "工资表"
    ws_p.append(PAYROLL_HEADERS)
    for r in COMMON:
        ws_p.append(list(r))
    for p, _ in BASE_DIFF:
        ws_p.append(list(p))
    for p, _ in AMOUNT_DIFF:
        ws_p.append(list(p))
    for r in PAYROLL_ONLY:
        ws_p.append(list(r))
    p_path = OUT_DIR / "工资表_社保_脱敏样例.xlsx"
    wb_p.save(p_path)
    print(f"已生成 {p_path}，共 {ws_p.max_row - 1} 行")

    # 社保申报表
    wb_s = openpyxl.Workbook()
    ws_s = wb_s.active
    ws_s.title = "社保申报"
    ws_s.append(SOCIAL_HEADERS)
    for r in COMMON:
        # 工号, 姓名, si_base, hf_base, si_person, si_company, hf_person, hf_company
        ws_s.append([r[0], r[1], r[3], r[4], r[5], r[6], r[7], r[8]])
    for _, s in BASE_DIFF:
        ws_s.append(list(s))
    for _, s in AMOUNT_DIFF:
        ws_s.append(list(s))
    for r in SOCIAL_ONLY:
        ws_s.append(list(r))
    s_path = OUT_DIR / "社保申报表_脱敏样例.xlsx"
    wb_s.save(s_path)
    print(f"已生成 {s_path}，共 {ws_s.max_row - 1} 行")


if __name__ == "__main__":
    main()
